const PATTERNS: [RegExp, string][] = [
  [/^(\d+) smart devices selected$/i, '$1 جهازاً ذكياً'], [/^(\d+)\. (.+)$/, ''], [/^vat (\d+)%$/i, 'ضريبة القيمة المضافة $1%'],
]
export function translate(text: string): string | null {
  const key = text.trim().replace(/\s+/g, ' ')
  if (!key) return null
  const hit = AR[key.toLowerCase()]
  if (hit) return text.replace(text.trim(), () => hit)
  for (const [re, to] of PATTERNS) {
    const m = key.match(re)
    if (!m) continue
    if (to) return key.replace(re, to)
    const rest = AR[m[2].toLowerCase()] // numbered step names
    if (rest) return `${m[1]}. ${rest}`
  }
  return null
}

const ATTRS = ['placeholder', 'aria-label', 'title']
const skip = (el: Element | null) => !el || !!el.closest('[data-no-i18n], script, style, textarea')
function apply(node: Node) {
  if (node.nodeType === Node.TEXT_NODE) {
    if (skip(node.parentElement)) return
    const t = translate(node.nodeValue || ''); if (t !== null && t !== node.nodeValue) node.nodeValue = t
    return
  }
  if (!(node instanceof Element) || node.closest('[data-no-i18n]')) return
  for (const a of ATTRS) { const v = node.getAttribute(a), t = v && translate(v); if (t && t !== v) node.setAttribute(a, t) }
  node.childNodes.forEach(apply)
}

export function startArabic() {
  document.documentElement.lang = 'ar'; document.documentElement.dir = 'rtl'
  apply(document.body)
  const seen = new MutationObserver((list) => { for (const m of list) { if (m.type === 'childList') m.addedNodes.forEach(apply); else apply(m.target) } })
  seen.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS })
  return () => seen.disconnect()
}
